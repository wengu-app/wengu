// Generates everything the sandbox needs that has to exist as *text*:
//   src/generated/frame-bootstrap.ts  the in-frame runtime as a string (inlined into the sandbox document)
//   generated/sandbox.html            the sandbox document, for serving from a separate origin
//   generated/libs/three.json         LibraryBundle: bare specifier -> self-contained ES module source
//
// Libraries are bundled so that every module is importable from a blob: URL inside the frame: blob: URLs are not
// hierarchical, so relative imports between files cannot resolve. Each module may only import other *bare*
// specifiers, which the frame's import map points at sibling blob URLs.

import * as esbuild from 'esbuild';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const require = createRequire(import.meta.url);
const out = (...p) => path.join(pkgRoot, ...p);

await mkdir(out('src/generated'), { recursive: true });
await mkdir(out('generated/libs'), { recursive: true });

// ------------------------------------------------------------------------------------------ wengu/card primitive
const cardBuilt = await esbuild.build({
  entryPoints: [out('src/primitives/card.ts')],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const cardJs = cardBuilt.outputFiles[0].text;
await writeFile(
  out('src/generated/card-primitive.ts'),
  `// Generated by scripts/build-frame.mjs. Do not edit.\nexport const CARD_PRIMITIVE_JS: string = ${JSON.stringify(cardJs)};\n`,
);

// ------------------------------------------------------------------------------------------ bootstrap
const boot = await esbuild.build({
  entryPoints: [out('src/frame/bootstrap.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const bootstrapJs = boot.outputFiles[0].text;
await writeFile(
  out('src/generated/frame-bootstrap.ts'),
  `// Generated by scripts/build-frame.mjs. Do not edit.\nexport const FRAME_BOOTSTRAP_JS: string = ${JSON.stringify(bootstrapJs)};\n`,
);

// sandbox.html for the `url` delivery mode: same document as srcdoc. Import the TS builder via Node's type stripping.
const { buildFrameDocument } = await import(pathToFileURL(out('src/frame-document.ts')).href);
await writeFile(out('generated/sandbox.html'), buildFrameDocument());

// ------------------------------------------------------------------------------------------ three.js
const threeRoot = path.resolve(path.dirname(require.resolve('three')), '..');
const threePkg = JSON.parse(await readFile(path.join(threeRoot, 'package.json'), 'utf8'));
const jsmDir = path.join(threeRoot, 'examples/jsm');

/** Addons offered to components. Their transitive addon dependencies are added automatically. */
const ADDONS = [
  'controls/OrbitControls.js',
  'controls/TrackballControls.js',
  'controls/DragControls.js',
  'controls/TransformControls.js',
  'renderers/CSS2DRenderer.js',
  'renderers/CSS3DRenderer.js',
  'environments/RoomEnvironment.js',
  'geometries/RoundedBoxGeometry.js',
  'geometries/ConvexGeometry.js',
  'geometries/ParametricGeometry.js',
  'utils/BufferGeometryUtils.js',
  'lines/Line2.js',
  'lines/LineMaterial.js',
  'lines/LineGeometry.js',
  'postprocessing/EffectComposer.js',
  'postprocessing/RenderPass.js',
  'postprocessing/UnrealBloomPass.js',
  'postprocessing/OutputPass.js',
];

/** Rewrites `three` and cross-addon relative imports to bare externals. */
const externalizeAddons = (selfRel) => ({
  name: 'externalize-addons',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: 'three', external: true }));
    b.onResolve({ filter: /^\.\.?\// }, (args) => {
      const abs = path.resolve(args.resolveDir, args.path);
      const rel = path.relative(jsmDir, abs).split(path.sep).join('/');
      if (rel.startsWith('..') || rel === selfRel) return undefined;
      return { path: `three/addons/${rel}`, external: true };
    });
  },
});

const modules = {};
const minify = true;
const core = await esbuild.build({
  entryPoints: [path.join(threeRoot, 'build/three.module.js')],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify,
  write: false,
  legalComments: 'inline',
});
modules['three'] = core.outputFiles[0].text;

const queue = [...ADDONS];
const done = new Set();
while (queue.length) {
  const rel = queue.shift();
  if (done.has(rel)) continue;
  done.add(rel);
  const r = await esbuild.build({
    entryPoints: [path.join(jsmDir, rel)],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    minify,
    write: false,
    metafile: true,
    plugins: [externalizeAddons(rel)],
  });
  modules[`three/addons/${rel}`] = r.outputFiles[0].text;
  for (const input of Object.values(r.metafile.inputs)) {
    for (const imp of input.imports) {
      if (imp.external && imp.path.startsWith('three/addons/')) queue.push(imp.path.slice('three/addons/'.length));
    }
  }
}

const scene3dBuilt = await esbuild.build({
  entryPoints: [out('src/primitives/scene3d.ts')],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify,
  write: false,
  legalComments: 'none',
  external: ['three', 'three/addons/*'],
});
modules['wengu/scene3d'] = scene3dBuilt.outputFiles[0].text;

const bundle = { id: 'three', version: threePkg.version, modules };
await writeFile(out('generated/libs/three.json'), JSON.stringify(bundle));

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
console.log(
  `card ${kb(cardJs)}; bootstrap ${kb(bootstrapJs)}; three ${threePkg.version}: ${Object.keys(modules).length} modules, ${kb(JSON.stringify(bundle))}`,
);
