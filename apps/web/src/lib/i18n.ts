export type Lang = "zh" | "en";
export const DICTS: Record<Lang, Record<MessageKey, string>> = { en, zh };

export function resolveLang(pref: LangPref): Lang {
  if (pref !== "system") return pref;
  const langs = typeof navigator !== "undefined" ? (navigator.languages ?? [navigator.language]) : [];
  for (const l of langs) {
    if (/^zh\b/i.test(l)) return "zh";
    if (/^en\b/i.test(l)) return "en";
  }
  return "en";
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const dict = DICTS[lang];
  return (key, params) => {
    const s = dict[key] ?? en[key] ?? key;
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, (w, k: string) => (k in params ? String(params[k]) : w));
  };
}

const cache = new Map<Lang, Translate>();

export function useLang(): Lang {
  return resolveLang(useSettings().lang);
}

export function useT(): Translate {
  const lang = useLang();
  let t = cache.get(lang);
  if (!t) cache.set(lang, (t = translator(lang)));
  return t;
}

const RATING_KEYS: Record<string, MessageKey> = { again: "review.again", hard: "review.hard", good: "review.good", easy: "review.easy" };

/** Core's undo labels are English identifiers ("Answer good", "Suspend"); this shows them in the UI language. */
export function undoLabelText(label: string, t: Translate): string {
  const m = /^Answer (\w+)$/.exec(label);
  if (m) return t("undo.Answer", { rating: t(RATING_KEYS[m[1]!.toLowerCase()] ?? "review.good") });
  const key = `undo.${label}` as MessageKey;
  return key in en ? t(key) : label;
}
